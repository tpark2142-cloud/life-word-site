-- Gallery visitors may post a short reaction or reflection.
-- Only the site administrator may edit existing visitor entries.

create table if not exists public.gallery_feedback (
  id bigint generated by default as identity primary key,
  gallery_id text not null,
  language text not null default 'en' check (language in ('en', 'ko')),
  reaction_emoji text,
  message text not null default '',
  created_at timestamptz not null default now(),
  is_visible boolean not null default true,
  constraint gallery_feedback_content_check
    check (length(message) <= 220 and (coalesce(length(reaction_emoji), 0) <= 12) and (message <> '' or coalesce(reaction_emoji, '') <> ''))
);

alter table public.gallery_feedback add column if not exists gallery_id text;
alter table public.gallery_feedback add column if not exists language text not null default 'en';
alter table public.gallery_feedback add column if not exists reaction_emoji text;
alter table public.gallery_feedback add column if not exists message text not null default '';
alter table public.gallery_feedback add column if not exists created_at timestamptz not null default now();
alter table public.gallery_feedback add column if not exists is_visible boolean not null default true;

alter table public.gallery_feedback enable row level security;

grant select, insert on public.gallery_feedback to anon, authenticated;
grant update on public.gallery_feedback to authenticated;

drop policy if exists "Anyone can read visible gallery feedback" on public.gallery_feedback;
create policy "Anyone can read visible gallery feedback"
  on public.gallery_feedback for select
  to anon, authenticated
  using (is_visible = true);

drop policy if exists "Anyone can post gallery feedback" on public.gallery_feedback;
create policy "Anyone can post gallery feedback"
  on public.gallery_feedback for insert
  to anon, authenticated
  with check (
    is_visible = true
    and language in ('en', 'ko')
    and length(message) <= 220
    and coalesce(length(reaction_emoji), 0) <= 12
    and (message <> '' or coalesce(reaction_emoji, '') <> '')
  );

drop policy if exists "Only site admin can edit gallery feedback" on public.gallery_feedback;
create policy "Only site admin can edit gallery feedback"
  on public.gallery_feedback for update
  to authenticated
  using ((auth.jwt() ->> 'email') = 'tpark2142@gmail.com')
  with check ((auth.jwt() ->> 'email') = 'tpark2142@gmail.com');

create or replace function public.admin_update_gallery_feedback(
  feedback_id bigint,
  emoji_value text,
  message_value text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if (auth.jwt() ->> 'email') is distinct from 'tpark2142@gmail.com' then
    raise exception 'Only the site administrator may edit gallery feedback.';
  end if;

  update public.gallery_feedback
  set reaction_emoji = nullif(left(coalesce(emoji_value, ''), 12), ''),
      message = left(coalesce(message_value, ''), 220)
  where id = feedback_id;

  if not found then
    raise exception 'Gallery feedback entry not found.';
  end if;
end;
$$;

revoke all on function public.admin_update_gallery_feedback(bigint, text, text) from public;
grant execute on function public.admin_update_gallery_feedback(bigint, text, text) to authenticated;

create index if not exists gallery_feedback_visible_recent_idx
  on public.gallery_feedback (is_visible, created_at desc);
